from collections import Counter
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
RAW_ROOT = 'https://raw.githubusercontent.com/EdmundWong98/personal-proxy-rules/main/'
COLLECTIONS = [
    ('OverseasAI', '海外 AI', ['ChatGPT', 'Claude', 'Copilot', 'Gemini']),
    ('OverseasStreaming', '海外流媒体', ['YouTube', 'Twitch', 'Netflix', 'HBO']),
    ('OverseasSocial', '海外社交软件', ['Instagram', 'Twitter', 'Telegram', 'Facebook']),
]
SOCIAL_AI_RULES = {
    'Twitter': {'DOMAIN-SUFFIX,grok.com'},
    'Facebook': {
        'DOMAIN-SUFFIX,llama.com',
        'DOMAIN-SUFFIX,meta.ai',
        'DOMAIN-SUFFIX,metaaiusercontent.com',
        'DOMAIN-SUFFIX,metaaivm.com',
        'DOMAIN-SUFFIX,muse.ai',
    },
}


def read_rules(platform):
    path = ROOT / 'proxy' / (platform + '.list')
    return [
        ','.join(part.strip() for part in line.split(','))
        for line in path.read_text(encoding='utf-8').splitlines()
        if line.strip() and not line.lstrip().startswith('#')
    ]


def main():
    platforms = {
        platform
        for _, _, members in COLLECTIONS
        for platform in members
    }
    sources = {platform: read_rules(platform) for platform in platforms}
    extra_ai = []
    for platform, selected in SOCIAL_AI_RULES.items():
        missing = selected - set(sources[platform])
        if missing:
            raise ValueError('Missing AI rules in {}: {}'.format(platform, sorted(missing)))
        extra_ai.extend(rule for rule in sources[platform] if rule in selected)
    ai_rules = set(extra_ai)
    outputs = {}
    for name, title, members in COLLECTIONS:
        entries = [rule for platform in members for rule in sources[platform]]
        provenance = list(members)
        if name == 'OverseasAI':
            entries.extend(extra_ai)
            provenance.extend(SOCIAL_AI_RULES)
        if name == 'OverseasSocial':
            entries = [rule for rule in entries if rule not in ai_rules]
        entries = list(dict.fromkeys(entries))
        counts = Counter(rule.split(',')[0] for rule in entries)
        header = [
            '# NAME: ' + title,
            '# MAINTAINER: EdmundWong98',
            '# GENERATED BY: scripts/build_collections.py',
        ]
        header.extend('# SOURCE: ' + RAW_ROOT + 'proxy/' + member + '.list' for member in provenance)
        header.extend('# {}: {}'.format(kind, count) for kind, count in sorted(counts.items()))
        header.append('# TOTAL: {}'.format(len(entries)))
        outputs[ROOT / 'proxy' / (name + '.list')] = '\n'.join(header + entries) + '\n'
    outputs[ROOT / 'categories.list'] = '\n'.join(
        RAW_ROOT + 'proxy/' + name + '.list,policy=PROXY,tag=' + name + ',desc=' + title
        for name, title, _ in COLLECTIONS
    ) + '\n'
    for path, content in outputs.items():
        path.write_text(content, encoding='utf-8')
        print(path.relative_to(ROOT))


if __name__ == '__main__':
    main()
